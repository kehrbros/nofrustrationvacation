-- Recurring market schedule of an order or offer, see MarketScheduling
CREATE TABLE market_scheduling (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type                VARCHAR(16) NOT NULL,
    scheduling_interval VARCHAR(16) NOT NULL,
    time_of_day         TIME        NOT NULL,
    day_of_month        INTEGER,
    lead_time           BIGINT,
    tokens_per_cycle    BIGINT,
    min_unused_tokens   BIGINT
);

CREATE TABLE market_scheduling_day (
    market_scheduling_id BIGINT      NOT NULL,
    day_of_week          VARCHAR(16) NOT NULL,
    PRIMARY KEY (market_scheduling_id, day_of_week),
    CONSTRAINT fk_market_scheduling_day_scheduling FOREIGN KEY (market_scheduling_id) REFERENCES market_scheduling (id)
);

-- Existing orders and offers keep NULL: they are one-off, not scheduled
ALTER TABLE consumer_order ADD COLUMN market_scheduling_id BIGINT;
ALTER TABLE consumer_order ADD CONSTRAINT fk_consumer_order_market_scheduling FOREIGN KEY (market_scheduling_id) REFERENCES market_scheduling (id);
ALTER TABLE provider_offer ADD COLUMN market_scheduling_id BIGINT;
ALTER TABLE provider_offer ADD CONSTRAINT fk_provider_offer_market_scheduling FOREIGN KEY (market_scheduling_id) REFERENCES market_scheduling (id);