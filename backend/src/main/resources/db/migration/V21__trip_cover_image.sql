-- Title photo of a trip, see Docs/domain.md. BYTEA exists in PostgreSQL and H2.
CREATE TABLE trip_cover_image (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id      BIGINT                      NOT NULL,
    source       VARCHAR(16)                 NOT NULL,
    content_type VARCHAR(64)                 NOT NULL,
    content      BYTEA                       NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_trip_cover_image_trip UNIQUE (trip_id),
    CONSTRAINT fk_trip_cover_image_trip FOREIGN KEY (trip_id) REFERENCES trip (id) ON DELETE CASCADE
);
