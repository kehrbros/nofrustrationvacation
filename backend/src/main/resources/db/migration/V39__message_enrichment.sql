-- What the model read from the text of a traffic event, once per text, see Docs/traffic-feed.md#anreicherung-messageenrichment
CREATE TABLE message_enrichment (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id    BIGINT                      NOT NULL,
    subject_id   VARCHAR(255)                NOT NULL,
    message_hash VARCHAR(64)                 NOT NULL,
    result       VARCHAR(100000)             NOT NULL,
    model        VARCHAR(100),
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_message_enrichment UNIQUE (source_id, subject_id, message_hash),
    CONSTRAINT fk_message_enrichment_source FOREIGN KEY (source_id) REFERENCES event_source (id)
);

-- Failed attempts to catch up the enrichment of an event
ALTER TABLE input_event ADD COLUMN enrichment_attempts SMALLINT DEFAULT 0 NOT NULL;

-- Events processed before there was a model: catch up, otherwise an event whose text never changes is never read.
-- Superseded versions and ended events are settled without asking.
UPDATE input_event SET enrichment_pending = TRUE
WHERE kind = 'TRAFFIC' AND message_hash IS NOT NULL AND processed_at IS NOT NULL;
