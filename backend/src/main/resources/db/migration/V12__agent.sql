-- Agents of providers: LLM access with encrypted API key, see Docs/agents.md
CREATE TABLE agent (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_user_id       BIGINT                      NOT NULL,
    name              VARCHAR(100)                NOT NULL,
    model_provider    VARCHAR(50)                 NOT NULL,
    base_url          VARCHAR(255),
    api_key_encrypted VARCHAR(1024)               NOT NULL,
    api_key_hint      VARCHAR(8)                  NOT NULL,
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_agent_app_user FOREIGN KEY (app_user_id) REFERENCES app_user (id)
);
CREATE INDEX ix_agent_app_user ON agent (app_user_id);

-- api_key_encrypted is not audited, so no copy of a key stays in the history
CREATE TABLE agent_aud (
    id             BIGINT NOT NULL,
    rev            BIGINT NOT NULL,
    revtype        TINYINT,
    app_user_id    BIGINT,
    name           VARCHAR(100),
    model_provider VARCHAR(50),
    base_url       VARCHAR(255),
    api_key_hint   VARCHAR(8),
    created_at     TIMESTAMP(6) WITH TIME ZONE,
    PRIMARY KEY (id, rev),
    CONSTRAINT fk_agent_aud_revinfo FOREIGN KEY (rev) REFERENCES revinfo (rev)
);
