-- Details of an accommodation booking, 0..1 per booking, deleted with it
CREATE TABLE booking_accommodation (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id      BIGINT       NOT NULL,
    name            VARCHAR(255) NOT NULL,
    address_line    VARCHAR(500),
    country_code    VARCHAR(2),
    latitude        DOUBLE PRECISION,
    longitude       DOUBLE PRECISION,
    time_zone       VARCHAR(64)  NOT NULL,
    phone           VARCHAR(64),
    email           VARCHAR(255),
    website         VARCHAR(1000),
    place_ref       VARCHAR(255),
    check_in_from   TIME,
    check_in_until  TIME,
    check_out_until TIME,
    guests          INTEGER,
    rooms           INTEGER,
    CONSTRAINT uk_booking_accommodation_booking UNIQUE (booking_id),
    CONSTRAINT fk_booking_accommodation_booking FOREIGN KEY (booking_id) REFERENCES booking (id) ON DELETE CASCADE,
    CONSTRAINT ck_booking_accommodation_coordinates CHECK ((latitude IS NULL) = (longitude IS NULL))
);

CREATE TABLE booking_accommodation_aud (
    id              BIGINT NOT NULL,
    rev             BIGINT NOT NULL,
    revtype         SMALLINT,
    booking_id      BIGINT,
    name            VARCHAR(255),
    address_line    VARCHAR(500),
    country_code    VARCHAR(2),
    latitude        DOUBLE PRECISION,
    longitude       DOUBLE PRECISION,
    time_zone       VARCHAR(64),
    phone           VARCHAR(64),
    email           VARCHAR(255),
    website         VARCHAR(1000),
    place_ref       VARCHAR(255),
    check_in_from   TIME,
    check_in_until  TIME,
    check_out_until TIME,
    guests          INTEGER,
    rooms           INTEGER,
    PRIMARY KEY (id, rev),
    CONSTRAINT fk_booking_accommodation_aud_revinfo FOREIGN KEY (rev) REFERENCES revinfo (rev)
);
