-- Monetary values in the base currency with 8 decimal places, see Docs/money.md.
-- Previously NUMERIC(38, 2), which cut token prices like 0.075 per million tokens.
ALTER TABLE app_user ALTER COLUMN account_balance SET DATA TYPE NUMERIC(19, 8);
ALTER TABLE consumer_order ALTER COLUMN min_cost_per_million_tokens SET DATA TYPE NUMERIC(19, 8);
ALTER TABLE consumer_order ALTER COLUMN max_cost_per_million_tokens SET DATA TYPE NUMERIC(19, 8);
ALTER TABLE provider_offer ALTER COLUMN price_per_million_input_tokens SET DATA TYPE NUMERIC(19, 8);
ALTER TABLE provider_offer ALTER COLUMN price_per_million_output_tokens SET DATA TYPE NUMERIC(19, 8);
ALTER TABLE agreement ALTER COLUMN agreed_price_per_million_input_tokens SET DATA TYPE NUMERIC(19, 8);
ALTER TABLE agreement ALTER COLUMN agreed_price_per_million_output_tokens SET DATA TYPE NUMERIC(19, 8);
ALTER TABLE agreement_aud ALTER COLUMN agreed_price_per_million_input_tokens SET DATA TYPE NUMERIC(19, 8);
ALTER TABLE agreement_aud ALTER COLUMN agreed_price_per_million_output_tokens SET DATA TYPE NUMERIC(19, 8);

-- Currency API responses are converted to, NULL means base currency
ALTER TABLE app_user ADD COLUMN preferred_currency VARCHAR(3);

-- Daily exchange rates: rate = units of currency per one unit of the base currency
CREATE TABLE exchange_rate (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    currency   VARCHAR(3)                  NOT NULL,
    rate       NUMERIC(19, 10)             NOT NULL,
    rate_date  DATE                        NOT NULL,
    fetched_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    source     VARCHAR(255)                NOT NULL,
    CONSTRAINT uk_exchange_rate_currency_date UNIQUE (currency, rate_date)
);
