-- Templates for recurring orders and offers, placed by a market scheduling (market/entities)
CREATE TABLE market_scheduling (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type                VARCHAR(16) NOT NULL,
    scheduling_interval VARCHAR(16) NOT NULL,
    time_of_day         TIME        NOT NULL,
    day_of_month        INTEGER,
    lead_time           BIGINT,
    tokens_per_cycle    BIGINT,
    min_unused_tokens   BIGINT
);

-- Weekdays of a WEEKLY scheduling
CREATE TABLE market_scheduling_day (
    market_scheduling_id BIGINT      NOT NULL,
    day_of_week          VARCHAR(16) NOT NULL,
    PRIMARY KEY (market_scheduling_id, day_of_week),
    CONSTRAINT fk_market_scheduling_day_scheduling FOREIGN KEY (market_scheduling_id) REFERENCES market_scheduling (id)
);

CREATE TABLE consumer_order_template (
    id                                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    max_cost_per_million_input_tokens  NUMERIC(19, 8),
    max_cost_per_million_output_tokens NUMERIC(19, 8),
    market_wait_time                  BIGINT,
    model_provider                    VARCHAR(255),
    model_name                        VARCHAR(255)
);

CREATE TABLE provider_offer_template (
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    price_per_million_input_tokens  NUMERIC(19, 8),
    price_per_million_output_tokens NUMERIC(19, 8),
    offered_until                   TIMESTAMP(6) WITH TIME ZONE,
    agent_id                        BIGINT NOT NULL,
    total_tokens                    BIGINT,
    market_scheduling_id            BIGINT,
    app_user_id                     BIGINT,
    CONSTRAINT fk_provider_offer_template_agent FOREIGN KEY (agent_id) REFERENCES agent (id),
    CONSTRAINT fk_provider_offer_template_scheduling FOREIGN KEY (market_scheduling_id) REFERENCES market_scheduling (id),
    CONSTRAINT fk_provider_offer_template_app_user FOREIGN KEY (app_user_id) REFERENCES app_user (id)
);
CREATE INDEX ix_provider_offer_template_app_user ON provider_offer_template (app_user_id);
