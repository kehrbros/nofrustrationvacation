-- One row per prompt sent to a provider's agent through an agreement, see Docs/llm.md
CREATE TABLE llm_protocol (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id          BIGINT                      NOT NULL,
    agreement_id      BIGINT                      NOT NULL,
    started_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    ended_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    prompt_tokens     BIGINT                      NOT NULL,
    completion_tokens BIGINT                      NOT NULL,
    total_tokens      BIGINT                      NOT NULL,
    success           BOOLEAN                     NOT NULL,
    CONSTRAINT fk_llm_protocol_agent FOREIGN KEY (agent_id) REFERENCES agent (id),
    CONSTRAINT fk_llm_protocol_agreement FOREIGN KEY (agreement_id) REFERENCES agreement (id)
);
CREATE INDEX ix_llm_protocol_agreement ON llm_protocol (agreement_id);