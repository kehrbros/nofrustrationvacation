-- Accounting with PayPal, see Docs/accounting.md and Docs/paypal.md.
-- Balances move from app_user.account_balance to one account per user and type (CREDIT, EARNINGS).

CREATE TABLE accounting_account (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_user_id BIGINT                      NOT NULL,
    type        VARCHAR(16)                 NOT NULL,
    balance     NUMERIC(19, 8)              NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_accounting_account_user_type UNIQUE (app_user_id, type),
    CONSTRAINT fk_accounting_account_app_user FOREIGN KEY (app_user_id) REFERENCES app_user (id),
    CONSTRAINT ck_accounting_account_balance CHECK (balance >= 0)
);

-- Append-only, the sum of an account's entries equals its balance
CREATE TABLE ledger_entry (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id   BIGINT                      NOT NULL,
    type         VARCHAR(32)                 NOT NULL,
    amount       NUMERIC(19, 8)              NOT NULL,
    reference_id BIGINT,
    booked_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_ledger_entry_account FOREIGN KEY (account_id) REFERENCES accounting_account (id)
);
CREATE INDEX ix_ledger_entry_account ON ledger_entry (account_id, booked_at);

INSERT INTO accounting_account (app_user_id, type, balance, created_at)
SELECT id, 'CREDIT', account_balance, CURRENT_TIMESTAMP FROM app_user WHERE account_balance > 0;
INSERT INTO ledger_entry (account_id, type, amount, booked_at)
SELECT id, 'OPENING_BALANCE', balance, created_at FROM accounting_account;
ALTER TABLE app_user DROP COLUMN account_balance;

-- PayPal account a provider gets paid out to, required for offers
CREATE TABLE payout_account (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_user_id         BIGINT                      NOT NULL,
    provider            VARCHAR(16)                 NOT NULL,
    external_account_id VARCHAR(255)                NOT NULL,
    email               VARCHAR(255),
    verified            BOOLEAN                     NOT NULL,
    linked_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_payout_account_app_user UNIQUE (app_user_id),
    CONSTRAINT fk_payout_account_app_user FOREIGN KEY (app_user_id) REFERENCES app_user (id)
);
CREATE INDEX ix_payout_account_external ON payout_account (provider, external_account_id);

CREATE TABLE payout_account_aud (
    id                  BIGINT   NOT NULL,
    rev                 BIGINT   NOT NULL,
    revtype             TINYINT,
    app_user_id         BIGINT,
    provider            VARCHAR(16),
    external_account_id VARCHAR(255),
    email               VARCHAR(255),
    verified            BOOLEAN,
    linked_at           TIMESTAMP(6) WITH TIME ZONE,
    PRIMARY KEY (id, rev),
    CONSTRAINT fk_payout_account_aud_revinfo FOREIGN KEY (rev) REFERENCES revinfo (rev)
);

-- "Log in with PayPal" started by a user, the state comes back with the redirect (CSRF protection)
CREATE TABLE payout_account_link_state (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    state       VARCHAR(64)                 NOT NULL,
    app_user_id BIGINT                      NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_payout_account_link_state UNIQUE (state)
);

CREATE TABLE top_up (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_user_id        BIGINT                      NOT NULL,
    amount             NUMERIC(19, 8)              NOT NULL,
    original_amount    NUMERIC(19, 8)              NOT NULL,
    original_currency  VARCHAR(3)                  NOT NULL,
    exchange_rate      NUMERIC(19, 10),
    exchange_rate_date DATE,
    status             VARCHAR(16)                 NOT NULL,
    paypal_order_id    VARCHAR(255),
    paypal_capture_id  VARCHAR(255),
    failure_reason     VARCHAR(255),
    created_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    completed_at       TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_top_up_paypal_order UNIQUE (paypal_order_id),
    CONSTRAINT fk_top_up_app_user FOREIGN KEY (app_user_id) REFERENCES app_user (id)
);

CREATE TABLE top_up_aud (
    id                 BIGINT NOT NULL,
    rev                BIGINT NOT NULL,
    revtype            TINYINT,
    app_user_id        BIGINT,
    amount             NUMERIC(19, 8),
    original_amount    NUMERIC(19, 8),
    original_currency  VARCHAR(3),
    exchange_rate      NUMERIC(19, 10),
    exchange_rate_date DATE,
    status             VARCHAR(16),
    paypal_order_id    VARCHAR(255),
    paypal_capture_id  VARCHAR(255),
    failure_reason     VARCHAR(255),
    created_at         TIMESTAMP(6) WITH TIME ZONE,
    completed_at       TIMESTAMP(6) WITH TIME ZONE,
    PRIMARY KEY (id, rev),
    CONSTRAINT fk_top_up_aud_revinfo FOREIGN KEY (rev) REFERENCES revinfo (rev)
);

CREATE TABLE payout (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_user_id               BIGINT                      NOT NULL,
    amount                    NUMERIC(19, 8)              NOT NULL,
    original_amount           NUMERIC(19, 8)              NOT NULL,
    original_currency         VARCHAR(3)                  NOT NULL,
    exchange_rate             NUMERIC(19, 10),
    exchange_rate_date        DATE,
    status                    VARCHAR(16)                 NOT NULL,
    receiver                  VARCHAR(255)                NOT NULL,
    paypal_batch_id           VARCHAR(255),
    paypal_transaction_status VARCHAR(32),
    failure_reason            VARCHAR(255),
    requested_at              TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    completed_at              TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_payout_app_user FOREIGN KEY (app_user_id) REFERENCES app_user (id)
);
CREATE INDEX ix_payout_status ON payout (status);

