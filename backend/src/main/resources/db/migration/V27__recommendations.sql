-- Route suggestions from scenarios: derived and replaced, not historized, see Docs/recommendations.md

CREATE TABLE suggestion_set (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id        BIGINT                      NOT NULL,
    trigger         VARCHAR(16)                 NOT NULL,
    waypoint_mode   VARCHAR(16)                 NOT NULL,
    consequence_id  BIGINT,
    incident_id     BIGINT,
    requested_count INTEGER                     NOT NULL,
    departure_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    basis_hash      VARCHAR(64)                 NOT NULL,
    status          VARCHAR(16)                 NOT NULL,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_suggestion_set_route FOREIGN KEY (route_id) REFERENCES route (id) ON DELETE CASCADE,
    CONSTRAINT fk_suggestion_set_consequence FOREIGN KEY (consequence_id) REFERENCES consequence (id)
        ON DELETE SET NULL,
    CONSTRAINT fk_suggestion_set_incident FOREIGN KEY (incident_id) REFERENCES incident (id) ON DELETE SET NULL
);
CREATE INDEX ix_suggestion_set_route ON suggestion_set (route_id, status);
CREATE INDEX ix_suggestion_set_expires ON suggestion_set (expires_at);

-- One suggestion of a set, rank 1 is the best
CREATE TABLE route_option (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    suggestion_set_id BIGINT                      NOT NULL,
    rank              INTEGER                     NOT NULL,
    kind              VARCHAR(16)                 NOT NULL,
    via               VARCHAR(255),
    departure_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    arrival_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    distance_m        DOUBLE PRECISION            NOT NULL,
    duration          BIGINT                      NOT NULL,
    waiting           BIGINT                      NOT NULL,
    delay             BIGINT                      NOT NULL,
    shared_ratio      DOUBLE PRECISION,
    geometry          geometry(LineString, 4326)  NOT NULL,
    applied_at        TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_route_option_rank UNIQUE (suggestion_set_id, rank),
    CONSTRAINT fk_route_option_set FOREIGN KEY (suggestion_set_id) REFERENCES suggestion_set (id) ON DELETE CASCADE
);

CREATE TABLE route_option_label (
    route_option_id BIGINT      NOT NULL,
    label           VARCHAR(32) NOT NULL,
    PRIMARY KEY (route_option_id, label),
    CONSTRAINT fk_route_option_label_option FOREIGN KEY (route_option_id) REFERENCES route_option (id)
        ON DELETE CASCADE
);

-- Via points that become waypoints when the suggestion is applied; waypoint_id: existing waypoint of the user
CREATE TABLE route_option_point (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_option_id BIGINT           NOT NULL,
    position        INTEGER          NOT NULL,
    latitude        DOUBLE PRECISION NOT NULL,
    longitude       DOUBLE PRECISION NOT NULL,
    road_hint       VARCHAR(255),
    waypoint_id     BIGINT,
    CONSTRAINT uk_route_option_point_position UNIQUE (route_option_id, position),
    CONSTRAINT fk_route_option_point_option FOREIGN KEY (route_option_id) REFERENCES route_option (id)
        ON DELETE CASCADE,
    CONSTRAINT fk_route_option_point_waypoint FOREIGN KEY (waypoint_id) REFERENCES waypoint (id) ON DELETE SET NULL
);

-- Incidents that still affect the suggestion
CREATE TABLE route_option_conflict (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_option_id BIGINT      NOT NULL,
    incident_id     BIGINT      NOT NULL,
    impact          VARCHAR(16) NOT NULL,
    delay           BIGINT,
    CONSTRAINT fk_route_option_conflict_option FOREIGN KEY (route_option_id) REFERENCES route_option (id)
        ON DELETE CASCADE,
    CONSTRAINT fk_route_option_conflict_incident FOREIGN KEY (incident_id) REFERENCES incident (id)
        ON DELETE CASCADE
);

-- Who set a waypoint: USER or SUGGESTION (created by applying a suggestion)
ALTER TABLE waypoint ADD COLUMN origin VARCHAR(16) DEFAULT 'USER' NOT NULL;
ALTER TABLE waypoint_aud ADD COLUMN origin VARCHAR(16);