-- Road network from OpenStreetMap via GraphHopper, replaces road/segment, see Docs/network.md

CREATE EXTENSION IF NOT EXISTS postgis;

-- One import per region
CREATE TABLE extract_version (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region        VARCHAR(16)                 NOT NULL,
    data_date     TIMESTAMP(6) WITH TIME ZONE,
    started_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    finished_at   TIMESTAMP(6) WITH TIME ZONE,
    status        VARCHAR(16)                 NOT NULL,
    segment_count INTEGER
);
CREATE INDEX ix_extract_version_region ON extract_version (region, status);

-- One drivable direction of a GraphHopper edge, id stays stable across imports
CREATE TABLE road_segment (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region                VARCHAR(16)                 NOT NULL,
    osm_way_id            BIGINT                      NOT NULL,
    -- Junction coordinates in 1e-7 degrees and geometry hash: business key, see Docs/network.md
    from_lat              INTEGER                     NOT NULL,
    from_lon              INTEGER                     NOT NULL,
    to_lat                INTEGER                     NOT NULL,
    to_lon                INTEGER                     NOT NULL,
    geometry_hash         INTEGER                     NOT NULL,
    ref                   VARCHAR(255),
    name                  VARCHAR(255),
    road_class            VARCHAR(32)                 NOT NULL,
    bridge                BOOLEAN                     NOT NULL,
    tunnel                BOOLEAN                     NOT NULL,
    length_m              DOUBLE PRECISION            NOT NULL,
    geometry              geometry(LineString, 4326)  NOT NULL,
    first_seen_version_id BIGINT                      NOT NULL,
    last_seen_version_id  BIGINT                      NOT NULL,
    retired_at            TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_road_segment_key UNIQUE (osm_way_id, from_lat, from_lon, to_lat, to_lon, geometry_hash),
    CONSTRAINT fk_road_segment_first_seen FOREIGN KEY (first_seen_version_id) REFERENCES extract_version (id),
    CONSTRAINT fk_road_segment_last_seen FOREIGN KEY (last_seen_version_id) REFERENCES extract_version (id)
);
CREATE INDEX ix_road_segment_geometry ON road_segment USING GIST (geometry);
CREATE INDEX ix_road_segment_region ON road_segment (region, last_seen_version_id);

-- GraphHopper edge_key (edge + direction) of one graph version -> segment, n:1
CREATE TABLE edge_mapping (
    extract_version_id BIGINT  NOT NULL,
    edge_key           INTEGER NOT NULL,
    road_segment_id    BIGINT  NOT NULL,
    PRIMARY KEY (extract_version_id, edge_key),
    CONSTRAINT fk_edge_mapping_version FOREIGN KEY (extract_version_id) REFERENCES extract_version (id),
    CONSTRAINT fk_edge_mapping_segment FOREIGN KEY (road_segment_id) REFERENCES road_segment (id)
);
-- All edge keys of a segment, e.g. to block it for routing
CREATE INDEX ix_edge_mapping_segment ON edge_mapping (road_segment_id, extract_version_id);

-- References to the old segments are meaningless, there is no real data (consequences go with route_section)
DELETE FROM incident_segment;
DELETE FROM route_section;

ALTER TABLE route_section DROP CONSTRAINT fk_route_section_segment;
ALTER TABLE route_section ADD CONSTRAINT fk_route_section_segment
    FOREIGN KEY (segment_id) REFERENCES road_segment (id);
ALTER TABLE incident_segment DROP CONSTRAINT fk_incident_segment_segment;
ALTER TABLE incident_segment ADD CONSTRAINT fk_incident_segment_segment
    FOREIGN KEY (segment_id) REFERENCES road_segment (id);

DROP TABLE segment;
DROP TABLE road;