-- Decision of the user on a run of the agent, see Docs/advisor.md#auswählen-und-verwerfen. The incident the run was
-- started for, kept when its consequence is replaced by a new assessment.
ALTER TABLE advisor_run
    ADD COLUMN incident_id     BIGINT,
    ADD COLUMN decision        VARCHAR(16),
    ADD COLUMN chosen_position INTEGER,
    ADD COLUMN decided_at      TIMESTAMP(6) WITH TIME ZONE,
    ADD CONSTRAINT fk_advisor_run_incident FOREIGN KEY (incident_id) REFERENCES incident (id) ON DELETE SET NULL,
    ADD CONSTRAINT ck_advisor_run_decision CHECK ((decision IS NULL AND decided_at IS NULL)
        OR (decision = 'DISMISSED' AND decided_at IS NOT NULL AND chosen_position IS NULL)
        OR (decision = 'ACCEPTED' AND decided_at IS NOT NULL AND chosen_position IS NOT NULL));
CREATE INDEX ix_advisor_run_incident ON advisor_run (incident_id);

-- What the user has to do about a booking after the trip changed, e.g. cancel it at the provider, see
-- Docs/domain.md#bookings. A copy of the booking, so it stays when the booking is deleted with its stop.
CREATE TABLE booking_todo (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id                  BIGINT                      NOT NULL,
    booking_id               BIGINT,
    kind                     VARCHAR(32)                 NOT NULL,
    reason                   VARCHAR(32)                 NOT NULL,
    title                    VARCHAR(255)                NOT NULL,
    provider                 VARCHAR(255),
    reference                VARCHAR(255),
    manage_url               VARCHAR(1000),
    phone                    VARCHAR(64),
    email                    VARCHAR(255),
    starts_at                TIMESTAMP(6) WITH TIME ZONE,
    starts_at_tz             INTEGER,
    ends_at                  TIMESTAMP(6) WITH TIME ZONE,
    ends_at_tz               INTEGER,
    cancellation_deadline    TIMESTAMP(6) WITH TIME ZONE,
    cancellation_deadline_tz INTEGER,
    booked_in_app            BOOLEAN                     NOT NULL,
    new_arrival_on           DATE,
    created_at               TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    done_at                  TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_booking_todo_trip FOREIGN KEY (trip_id) REFERENCES trip (id) ON DELETE CASCADE,
    CONSTRAINT fk_booking_todo_booking FOREIGN KEY (booking_id) REFERENCES booking (id) ON DELETE SET NULL
);
CREATE INDEX ix_booking_todo_trip ON booking_todo (trip_id);
CREATE INDEX ix_booking_todo_booking ON booking_todo (booking_id);
