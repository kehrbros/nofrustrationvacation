ALTER TABLE event_source ADD COLUMN last_success_at TIMESTAMP(6) WITH TIME ZONE;
ALTER TABLE event_source ADD COLUMN etag VARCHAR(255);
ALTER TABLE event_source ADD COLUMN last_modified VARCHAR(64);

ALTER TABLE input_event ADD COLUMN subject_id VARCHAR(255);
ALTER TABLE input_event ADD COLUMN message_hash VARCHAR(64);
ALTER TABLE input_event ADD COLUMN processing_note VARCHAR(500);
ALTER TABLE input_event ADD COLUMN enrichment_pending BOOLEAN DEFAULT FALSE NOT NULL;
CREATE INDEX ix_input_event_subject ON input_event (source_id, subject_id);

-- Last known version of each event of a source (subject), compared by FeedDiff on every poll
CREATE TABLE source_subject (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id     BIGINT                      NOT NULL,
    subject_id    VARCHAR(255)                NOT NULL,
    version       VARCHAR(255)                NOT NULL,
    message_hash  VARCHAR(64),
    missing_polls INTEGER                     NOT NULL,
    last_seen_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    cleared_at    TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_source_subject UNIQUE (source_id, subject_id),
    CONSTRAINT fk_source_subject_source FOREIGN KEY (source_id) REFERENCES event_source (id)
);
