-- Plans of several steps for an incident and their payment with one approval, see Docs/incident-plans.md.

-- The result of a plan, as the backend computed it; empty for proposals of a single step.
ALTER TABLE advisor_proposal
    ADD COLUMN plan_deadline     TIMESTAMP(6) WITH TIME ZONE,
    ADD COLUMN reaches_target    BOOLEAN,
    ADD COLUMN extra_nights      INTEGER,
    ADD COLUMN extra_cost        NUMERIC(12, 2),
    ADD COLUMN cost_currency     VARCHAR(3),
    ADD COLUMN affects_following BOOLEAN,
    ADD COLUMN new_target_name   VARCHAR(255);

CREATE TABLE advisor_proposal_step (
    id                           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposal_id                  BIGINT           NOT NULL,
    position                     INTEGER          NOT NULL,
    kind                         VARCHAR(32)      NOT NULL,
    route_kind                   VARCHAR(32),
    via                          VARCHAR(255),
    departure_at                 TIMESTAMP(6) WITH TIME ZONE,
    arrival_at                   TIMESTAMP(6) WITH TIME ZONE,
    waited_for                   TIMESTAMP(6) WITH TIME ZONE,
    distance_meters              DOUBLE PRECISION,
    duration                     BIGINT,
    place_name                   VARCHAR(255),
    latitude                     DOUBLE PRECISION,
    longitude                    DOUBLE PRECISION,
    booking_id                   BIGINT,
    arrival_on                   DATE,
    stay_hotel_id                VARCHAR(64),
    stay_offer_id                VARCHAR(1000),
    stay_hotel_name              VARCHAR(255),
    stay_latitude                DOUBLE PRECISION,
    stay_longitude               DOUBLE PRECISION,
    stay_place                   VARCHAR(255),
    stay_distance_meters         INTEGER,
    stay_check_in                DATE,
    stay_check_out               DATE,
    stay_guests                  INTEGER,
    stay_rooms                   INTEGER,
    stay_price                   NUMERIC(12, 2),
    stay_currency                VARCHAR(3),
    stay_refundable              BOOLEAN,
    stay_free_cancellation_until TIMESTAMP(6),
    stay_replaces_booking_id     BIGINT,
    CONSTRAINT fk_advisor_step_proposal FOREIGN KEY (proposal_id) REFERENCES advisor_proposal (id) ON DELETE CASCADE,
    CONSTRAINT fk_advisor_step_booking FOREIGN KEY (booking_id) REFERENCES booking (id) ON DELETE SET NULL,
    CONSTRAINT fk_advisor_step_stay_booking FOREIGN KEY (stay_replaces_booking_id) REFERENCES booking (id)
        ON DELETE SET NULL,
    CONSTRAINT uk_advisor_step_position UNIQUE (proposal_id, position),
    CONSTRAINT ck_advisor_step_stay CHECK (stay_hotel_id IS NULL OR (stay_offer_id IS NOT NULL
        AND stay_check_out > stay_check_in AND stay_price >= 0 AND stay_currency IS NOT NULL))
);
CREATE INDEX ix_advisor_step_booking ON advisor_proposal_step (booking_id);
CREATE INDEX ix_advisor_step_stay_booking ON advisor_proposal_step (stay_replaces_booking_id);

CREATE TABLE advisor_proposal_step_point (
    step_id     BIGINT           NOT NULL,
    position    INTEGER          NOT NULL,
    latitude    DOUBLE PRECISION NOT NULL,
    longitude   DOUBLE PRECISION NOT NULL,
    road_hint   VARCHAR(255),
    waypoint_id BIGINT,
    PRIMARY KEY (step_id, position),
    CONSTRAINT fk_advisor_step_point_step FOREIGN KEY (step_id) REFERENCES advisor_proposal_step (id) ON DELETE CASCADE,
    CONSTRAINT fk_advisor_step_point_waypoint FOREIGN KEY (waypoint_id) REFERENCES waypoint (id) ON DELETE SET NULL
);
CREATE INDEX ix_advisor_step_point_waypoint ON advisor_proposal_step_point (waypoint_id);

-- One PayPal order for all hotels of a plan; the hotels are booking_reservation rows pointing here.
CREATE TABLE plan_payment (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_user_id     BIGINT                      NOT NULL,
    status          VARCHAR(16)                 NOT NULL,
    paypal_order_id VARCHAR(64),
    total           NUMERIC(12, 2)              NOT NULL,
    currency        VARCHAR(3)                  NOT NULL,
    failure         VARCHAR(500),
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    secured_at      TIMESTAMP(6) WITH TIME ZONE,
    settled_at      TIMESTAMP(6) WITH TIME ZONE,
    attempted_at    TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_plan_payment_app_user FOREIGN KEY (app_user_id) REFERENCES app_user (id) ON DELETE CASCADE
);
CREATE INDEX ix_plan_payment_status ON plan_payment (status);

ALTER TABLE booking_reservation
    ADD COLUMN plan_payment_id BIGINT,
    ADD COLUMN plan_key        VARCHAR(32),
    ADD CONSTRAINT fk_booking_reservation_plan_payment FOREIGN KEY (plan_payment_id) REFERENCES plan_payment (id);
CREATE INDEX ix_booking_reservation_plan_payment ON booking_reservation (plan_payment_id);

-- A plan the user took: a copy of its steps (the run goes away when the plan splits the route), paid or not.
CREATE TABLE advisor_plan_execution (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_user_id     BIGINT                      NOT NULL,
    trip_id         BIGINT                      NOT NULL,
    route_id        BIGINT                      NOT NULL,
    run_id          BIGINT                      NOT NULL,
    proposal_rank   INTEGER                     NOT NULL,
    plan            TEXT                        NOT NULL,
    plan_payment_id BIGINT,
    status          VARCHAR(16)                 NOT NULL,
    failure         VARCHAR(500),
    outcome         TEXT,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    applied_at      TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_advisor_plan_execution_trip FOREIGN KEY (trip_id) REFERENCES trip (id) ON DELETE CASCADE,
    CONSTRAINT fk_advisor_plan_execution_payment FOREIGN KEY (plan_payment_id) REFERENCES plan_payment (id),
    CONSTRAINT uk_advisor_plan_execution_payment UNIQUE (plan_payment_id)
);
CREATE INDEX ix_advisor_plan_execution_trip ON advisor_plan_execution (trip_id);
