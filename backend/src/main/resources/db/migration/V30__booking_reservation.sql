-- Booking of an alternative accommodation via LiteAPI, paid with PayPal, one row per attempt, see
-- Docs/accommodation-alternatives.md. Holder data is kept only until the booking is made (needed after the PayPal
-- redirect), not audited.

CREATE TABLE booking_reservation (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stop_id                  BIGINT        NOT NULL,
    replaces_booking_id      BIGINT,
    booking_id               BIGINT,
    status                   VARCHAR(16)   NOT NULL,
    hotel_id                 VARCHAR(64)   NOT NULL,
    offer_id                 VARCHAR(1000) NOT NULL,
    prebook_id               VARCHAR(255)  NOT NULL,
    check_in                 DATE          NOT NULL,
    check_out                DATE          NOT NULL,
    guests                   INTEGER       NOT NULL,
    rooms                    INTEGER       NOT NULL,
    net_price                NUMERIC(12, 2) NOT NULL,
    fee                      NUMERIC(12, 2) NOT NULL,
    price                    NUMERIC(12, 2) NOT NULL,
    currency                 VARCHAR(3)    NOT NULL,
    refundable               BOOLEAN       NOT NULL,
    free_cancellation_until  TIMESTAMP(6),
    hotel_name               VARCHAR(255)  NOT NULL,
    hotel_address            VARCHAR(500),
    hotel_country_code       VARCHAR(2),
    hotel_latitude           DOUBLE PRECISION,
    hotel_longitude          DOUBLE PRECISION,
    hotel_phone              VARCHAR(64),
    hotel_email              VARCHAR(255),
    hotel_website            VARCHAR(1000),
    check_in_from            TIME,
    check_in_until           TIME,
    check_out_until          TIME,
    holder_first_name        VARCHAR(100),
    holder_last_name         VARCHAR(100),
    holder_email             VARCHAR(255),
    holder_phone             VARCHAR(64),
    paypal_order_id          VARCHAR(64),
    paypal_authorization_id  VARCHAR(64),
    paypal_capture_id        VARCHAR(64),
    provider_booking_id      VARCHAR(255),
    provider_confirmation    VARCHAR(255),
    failure                  VARCHAR(500),
    created_at               TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    booked_at                TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_booking_reservation_booking UNIQUE (booking_id),
    CONSTRAINT fk_booking_reservation_stop FOREIGN KEY (stop_id) REFERENCES stop (id),
    CONSTRAINT fk_booking_reservation_replaces FOREIGN KEY (replaces_booking_id) REFERENCES booking (id) ON DELETE SET NULL,
    CONSTRAINT fk_booking_reservation_booking FOREIGN KEY (booking_id) REFERENCES booking (id) ON DELETE SET NULL,
    CONSTRAINT ck_booking_reservation_period CHECK (check_out > check_in),
    CONSTRAINT ck_booking_reservation_price CHECK (net_price >= 0 AND fee >= 0 AND price = net_price + fee)
);

CREATE INDEX ix_booking_reservation_stop ON booking_reservation (stop_id);
