-- Places from OpenStreetMap for stays along a route, replaced per region by each import, see Docs/network.md
CREATE TABLE place (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region             VARCHAR(16)           NOT NULL,
    extract_version_id BIGINT                NOT NULL,
    name               VARCHAR(255)          NOT NULL,
    kind               VARCHAR(16)           NOT NULL,
    geometry           geometry(Point, 4326) NOT NULL,
    CONSTRAINT fk_place_extract_version FOREIGN KEY (extract_version_id) REFERENCES extract_version (id)
);
CREATE INDEX ix_place_geometry ON place USING GIST (geometry);
CREATE INDEX ix_place_region ON place (region);
