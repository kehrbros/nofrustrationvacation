-- Travel incidents: road network, trips, bookings, input, incidents, see Docs/domain.md

-- Road network
CREATE TABLE road (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number VARCHAR(32)  NOT NULL,
    name   VARCHAR(255),
    CONSTRAINT uk_road_number UNIQUE (number)
);

-- From junction to junction, one per direction
CREATE TABLE segment (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    road_id       BIGINT          NOT NULL,
    from_junction VARCHAR(255)    NOT NULL,
    to_junction   VARCHAR(255)    NOT NULL,
    geometry      VARCHAR(1000000) NOT NULL,
    CONSTRAINT uk_segment_road_from_to UNIQUE (road_id, from_junction, to_junction),
    CONSTRAINT fk_segment_road FOREIGN KEY (road_id) REFERENCES road (id)
);

-- Trips
CREATE TABLE trip (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_user_id BIGINT                      NOT NULL,
    name        VARCHAR(255)                NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_trip_app_user FOREIGN KEY (app_user_id) REFERENCES app_user (id)
);
CREATE INDEX ix_trip_app_user ON trip (app_user_id);

CREATE TABLE trip_aud (
    id          BIGINT NOT NULL,
    rev         BIGINT NOT NULL,
    revtype     SMALLINT,
    app_user_id BIGINT,
    name        VARCHAR(255),
    created_at  TIMESTAMP(6) WITH TIME ZONE,
    PRIMARY KEY (id, rev),
    CONSTRAINT fk_trip_aud_revinfo FOREIGN KEY (rev) REFERENCES revinfo (rev)
);

CREATE TABLE stop (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id      BIGINT       NOT NULL,
    position     INTEGER      NOT NULL,
    name         VARCHAR(255) NOT NULL,
    latitude     DOUBLE PRECISION,
    longitude    DOUBLE PRECISION,
    arrival_at   TIMESTAMP(6) WITH TIME ZONE,
    departure_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_stop_trip FOREIGN KEY (trip_id) REFERENCES trip (id)
);
CREATE INDEX ix_stop_trip ON stop (trip_id, position);

CREATE TABLE stop_aud (
    id           BIGINT NOT NULL,
    rev          BIGINT NOT NULL,
    revtype      SMALLINT,
    trip_id      BIGINT,
    position     INTEGER,
    name         VARCHAR(255),
    latitude     DOUBLE PRECISION,
    longitude    DOUBLE PRECISION,
    arrival_at   TIMESTAMP(6) WITH TIME ZONE,
    departure_at TIMESTAMP(6) WITH TIME ZONE,
    PRIMARY KEY (id, rev),
    CONSTRAINT fk_stop_aud_revinfo FOREIGN KEY (rev) REFERENCES revinfo (rev)
);

CREATE TABLE route (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id      BIGINT NOT NULL,
    from_stop_id BIGINT NOT NULL,
    to_stop_id   BIGINT NOT NULL,
    planned_at   TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_route_stops UNIQUE (from_stop_id, to_stop_id),
    CONSTRAINT fk_route_trip FOREIGN KEY (trip_id) REFERENCES trip (id),
    CONSTRAINT fk_route_from_stop FOREIGN KEY (from_stop_id) REFERENCES stop (id),
    CONSTRAINT fk_route_to_stop FOREIGN KEY (to_stop_id) REFERENCES stop (id)
);
CREATE INDEX ix_route_trip ON route (trip_id);

CREATE TABLE route_section (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id               BIGINT                      NOT NULL,
    position               INTEGER                     NOT NULL,
    segment_id             BIGINT                      NOT NULL,
    expected_passage_start TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expected_passage_end   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_route_section_position UNIQUE (route_id, position),
    CONSTRAINT fk_route_section_route FOREIGN KEY (route_id) REFERENCES route (id),
    CONSTRAINT fk_route_section_segment FOREIGN KEY (segment_id) REFERENCES segment (id),
    CONSTRAINT ck_route_section_passage CHECK (expected_passage_end >= expected_passage_start)
);
-- Index segment -> route section: finds the routes affected by an incident
CREATE INDEX ix_route_section_segment ON route_section (segment_id, expected_passage_start);

-- Bookings
CREATE TABLE booking (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stop_id   BIGINT       NOT NULL,
    type      VARCHAR(16)  NOT NULL,
    title     VARCHAR(255) NOT NULL,
    provider  VARCHAR(255),
    reference VARCHAR(255),
    starts_at TIMESTAMP(6) WITH TIME ZONE,
    ends_at   TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_booking_stop FOREIGN KEY (stop_id) REFERENCES stop (id)
);
CREATE INDEX ix_booking_stop ON booking (stop_id);

CREATE TABLE booking_aud (
    id        BIGINT NOT NULL,
    rev       BIGINT NOT NULL,
    revtype   SMALLINT,
    stop_id   BIGINT,
    type      VARCHAR(16),
    title     VARCHAR(255),
    provider  VARCHAR(255),
    reference VARCHAR(255),
    starts_at TIMESTAMP(6) WITH TIME ZONE,
    ends_at   TIMESTAMP(6) WITH TIME ZONE,
    PRIMARY KEY (id, rev),
    CONSTRAINT fk_booking_aud_revinfo FOREIGN KEY (rev) REFERENCES revinfo (rev)
);

-- Incidents
CREATE TABLE incident (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type           VARCHAR(16)                 NOT NULL,
    description    VARCHAR(2000),
    valid_from     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    valid_to       TIMESTAMP(6) WITH TIME ZONE,
    expected_delay BIGINT,
    CONSTRAINT ck_incident_validity CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

CREATE TABLE incident_aud (
    id             BIGINT NOT NULL,
    rev            BIGINT NOT NULL,
    revtype        SMALLINT,
    type           VARCHAR(16),
    description    VARCHAR(2000),
    valid_from     TIMESTAMP(6) WITH TIME ZONE,
    valid_to       TIMESTAMP(6) WITH TIME ZONE,
    expected_delay BIGINT,
    PRIMARY KEY (id, rev),
    CONSTRAINT fk_incident_aud_revinfo FOREIGN KEY (rev) REFERENCES revinfo (rev)
);

-- Location of an incident, 1..* segments
CREATE TABLE incident_segment (
    incident_id BIGINT NOT NULL,
    segment_id  BIGINT NOT NULL,
    PRIMARY KEY (incident_id, segment_id),
    CONSTRAINT fk_incident_segment_incident FOREIGN KEY (incident_id) REFERENCES incident (id),
    CONSTRAINT fk_incident_segment_segment FOREIGN KEY (segment_id) REFERENCES segment (id)
);
CREATE INDEX ix_incident_segment_segment ON incident_segment (segment_id);

CREATE TABLE incident_segment_aud (
    rev         BIGINT NOT NULL,
    revtype     SMALLINT,
    incident_id BIGINT NOT NULL,
    segment_id  BIGINT NOT NULL,
    PRIMARY KEY (rev, incident_id, segment_id),
    CONSTRAINT fk_incident_segment_aud_revinfo FOREIGN KEY (rev) REFERENCES revinfo (rev)
);

-- Derived, removed with the route or section it refers to
CREATE TABLE consequence (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id      BIGINT                      NOT NULL,
    route_id         BIGINT                      NOT NULL,
    route_section_id BIGINT                      NOT NULL,
    impact           VARCHAR(16)                 NOT NULL,
    delay            BIGINT,
    detected_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_consequence_incident_route UNIQUE (incident_id, route_id),
    CONSTRAINT fk_consequence_incident FOREIGN KEY (incident_id) REFERENCES incident (id),
    CONSTRAINT fk_consequence_route FOREIGN KEY (route_id) REFERENCES route (id) ON DELETE CASCADE,
    CONSTRAINT fk_consequence_route_section FOREIGN KEY (route_section_id) REFERENCES route_section (id) ON DELETE CASCADE
);
CREATE INDEX ix_consequence_route ON consequence (route_id);

-- Input
CREATE TABLE event_source (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(64) NOT NULL,
    type    VARCHAR(16) NOT NULL,
    enabled BOOLEAN     NOT NULL,
    CONSTRAINT uk_event_source_name UNIQUE (name)
);

-- All event subtypes, told apart by kind (TRAFFIC, WEBHOOK)
CREATE TABLE input_event (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind               VARCHAR(16)                 NOT NULL,
    source_id          BIGINT                      NOT NULL,
    external_id        VARCHAR(255),
    payload            VARCHAR(1000000)            NOT NULL,
    received_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    processed_at       TIMESTAMP(6) WITH TIME ZONE,
    incident_id        BIGINT,
    road_number        VARCHAR(255),
    description        VARCHAR(2000),
    starts_at          TIMESTAMP(6) WITH TIME ZONE,
    ends_at            TIMESTAMP(6) WITH TIME ZONE,
    signature_verified BOOLEAN,
    CONSTRAINT uk_input_event_external UNIQUE (source_id, external_id),
    CONSTRAINT fk_input_event_source FOREIGN KEY (source_id) REFERENCES event_source (id),
    CONSTRAINT fk_input_event_incident FOREIGN KEY (incident_id) REFERENCES incident (id)
);
CREATE INDEX ix_input_event_incident ON input_event (incident_id);
