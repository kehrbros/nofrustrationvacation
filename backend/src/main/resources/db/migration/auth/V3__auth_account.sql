-- Accounts of the own identity provider (package com.vacantagent.auth), see Docs/authentication.md.
-- No foreign keys to tables of other modules: the auth module can be replaced by an external IdP.
CREATE TABLE auth_account (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    email         VARCHAR(255),
    enabled       BOOLEAN      NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_auth_account_username UNIQUE (username)
);

CREATE TABLE auth_account_role (
    account_id BIGINT       NOT NULL,
    role       VARCHAR(255) NOT NULL,
    PRIMARY KEY (account_id, role),
    CONSTRAINT fk_auth_account_role_account FOREIGN KEY (account_id) REFERENCES auth_account (id)
);
