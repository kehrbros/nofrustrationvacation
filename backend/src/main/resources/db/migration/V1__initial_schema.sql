CREATE TABLE revinfo (
    rev      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revtstmp BIGINT NOT NULL
);

CREATE TABLE app_user (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(255),
    mail            VARCHAR(255),
    account_balance NUMERIC(38, 2)
);

CREATE TABLE consumer_order (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    min_cost_per_million_tokens NUMERIC(38, 2),
    max_cost_per_million_tokens NUMERIC(38, 2),
    market_wait_time   BIGINT
);

CREATE TABLE provider_offer (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    price_per_million_input_tokens  NUMERIC(38, 2),
    price_per_million_output_tokens NUMERIC(38, 2),
    offered_until          TIMESTAMP(6) WITH TIME ZONE,
    model_provider         VARCHAR(255),
    model_name             VARCHAR(255),
    last_error_at          TIMESTAMP(6) WITH TIME ZONE,
    last_success_at        TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE agreement (
    id                            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consumer_order_id             BIGINT,
    provider_offer_id             BIGINT,
    agreed_at                     TIMESTAMP(6) WITH TIME ZONE,
    valid_until                   TIMESTAMP(6) WITH TIME ZONE,
    agreed_price_per_million_input_tokens NUMERIC(38, 2),
    agreed_price_per_million_output_tokens NUMERIC(38, 2),
    CONSTRAINT fk_agreement_consumer_order FOREIGN KEY (consumer_order_id) REFERENCES consumer_order (id),
    CONSTRAINT fk_agreement_provider_offer FOREIGN KEY (provider_offer_id) REFERENCES provider_offer (id)
);

CREATE TABLE agreement_aud (
    id                            BIGINT NOT NULL,
    rev                           BIGINT NOT NULL,
    revtype                       TINYINT,
    consumer_order_id             BIGINT,
    provider_offer_id             BIGINT,
    agreed_at                     TIMESTAMP(6) WITH TIME ZONE,
    valid_until                   TIMESTAMP(6) WITH TIME ZONE,
    agreed_price_per_million_input_tokens NUMERIC(38, 2),
    agreed_price_per_million_output_tokens NUMERIC(38, 2),
    PRIMARY KEY (id, rev),
    CONSTRAINT fk_agreement_aud_revinfo FOREIGN KEY (rev) REFERENCES revinfo (rev)
);
