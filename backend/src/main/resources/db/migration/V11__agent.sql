-- Model and credentials of an offer move to agent. Each existing offer gets its own agent without secret.
CREATE TABLE agent (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_provider    VARCHAR(255),
    model_name        VARCHAR(255),
    secret            VARCHAR(255),
    provider_offer_id BIGINT
);
INSERT INTO agent (model_provider, model_name, provider_offer_id)
    SELECT model_provider, model_name, id FROM provider_offer;
ALTER TABLE provider_offer ADD COLUMN agent_id BIGINT;
UPDATE provider_offer o SET agent_id = (SELECT a.id FROM agent a WHERE a.provider_offer_id = o.id);
ALTER TABLE agent DROP COLUMN provider_offer_id;
ALTER TABLE provider_offer ADD CONSTRAINT fk_provider_offer_agent FOREIGN KEY (agent_id) REFERENCES agent (id);
ALTER TABLE provider_offer DROP COLUMN model_provider;
ALTER TABLE provider_offer DROP COLUMN model_name;