-- Route planning via network.Routing: driven part of a segment, waypoints chosen by the user, see Docs/domain.md

-- Driven part of the segment, below 0..1 only on the first and last section of a route
ALTER TABLE route_section ADD COLUMN from_fraction DOUBLE PRECISION DEFAULT 0 NOT NULL;
ALTER TABLE route_section ADD COLUMN to_fraction DOUBLE PRECISION DEFAULT 1 NOT NULL;
ALTER TABLE route_section ADD CONSTRAINT ck_route_section_fraction
    CHECK (from_fraction >= 0 AND to_fraction <= 1 AND from_fraction <= to_fraction);

-- Point the user wants to pass between the two stops of a route, without staying
CREATE TABLE waypoint (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id  BIGINT           NOT NULL,
    position  INTEGER          NOT NULL,
    latitude  DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    name      VARCHAR(255),
    road_hint VARCHAR(255),
    CONSTRAINT uk_waypoint_position UNIQUE (route_id, position),
    CONSTRAINT fk_waypoint_route FOREIGN KEY (route_id) REFERENCES route (id)
);

CREATE TABLE waypoint_aud (
    id        BIGINT NOT NULL,
    rev       BIGINT NOT NULL,
    revtype   SMALLINT,
    route_id  BIGINT,
    position  INTEGER,
    latitude  DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    name      VARCHAR(255),
    road_hint VARCHAR(255),
    PRIMARY KEY (id, rev),
    CONSTRAINT fk_waypoint_aud_revinfo FOREIGN KEY (rev) REFERENCES revinfo (rev)
);