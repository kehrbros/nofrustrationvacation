-- Runs and proposals of the agent, derived and not audited, see Docs/advisor.md#datenmodell.

CREATE TABLE advisor_run (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id       BIGINT                      NOT NULL,
    consequence_id BIGINT,
    run_trigger    VARCHAR(16)                 NOT NULL,
    goal           VARCHAR(16)                 NOT NULL,
    status         VARCHAR(32)                 NOT NULL,
    auto_key       VARCHAR(64),
    situation      VARCHAR(64)                 NOT NULL,
    summary        VARCHAR(2000),
    failure        VARCHAR(32),
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    finished_at    TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_advisor_run_route FOREIGN KEY (route_id) REFERENCES route (id) ON DELETE CASCADE,
    CONSTRAINT fk_advisor_run_consequence FOREIGN KEY (consequence_id) REFERENCES consequence (id) ON DELETE SET NULL,
    -- NULL does not collide: only automatic runs have a key
    CONSTRAINT uk_advisor_run_auto_key UNIQUE (route_id, auto_key)
);
CREATE INDEX ix_advisor_run_consequence ON advisor_run (consequence_id);

CREATE TABLE advisor_proposal (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id          BIGINT                      NOT NULL,
    position        INTEGER                     NOT NULL,
    kind            VARCHAR(32)                 NOT NULL,
    reason          VARCHAR(1000),
    via             VARCHAR(255),
    departure_at    TIMESTAMP(6) WITH TIME ZONE,
    arrival_at      TIMESTAMP(6) WITH TIME ZONE,
    distance_meters DOUBLE PRECISION,
    duration        BIGINT,
    delay           BIGINT,
    shared_ratio    DOUBLE PRECISION,
    meets_deadline  BOOLEAN,
    CONSTRAINT fk_advisor_proposal_run FOREIGN KEY (run_id) REFERENCES advisor_run (id) ON DELETE CASCADE,
    CONSTRAINT uk_advisor_proposal_position UNIQUE (run_id, position)
);

CREATE TABLE advisor_proposal_point (
    proposal_id BIGINT           NOT NULL,
    position    INTEGER          NOT NULL,
    latitude    DOUBLE PRECISION NOT NULL,
    longitude   DOUBLE PRECISION NOT NULL,
    road_hint   VARCHAR(255),
    waypoint_id BIGINT,
    PRIMARY KEY (proposal_id, position),
    CONSTRAINT fk_advisor_point_proposal FOREIGN KEY (proposal_id) REFERENCES advisor_proposal (id) ON DELETE CASCADE,
    CONSTRAINT fk_advisor_point_waypoint FOREIGN KEY (waypoint_id) REFERENCES waypoint (id) ON DELETE SET NULL
);
CREATE INDEX ix_advisor_point_waypoint ON advisor_proposal_point (waypoint_id);

CREATE TABLE advisor_proposal_conflict (
    proposal_id BIGINT      NOT NULL,
    incident_id BIGINT      NOT NULL,
    impact      VARCHAR(16) NOT NULL,
    delay       BIGINT,
    PRIMARY KEY (proposal_id, incident_id),
    CONSTRAINT fk_advisor_conflict_proposal FOREIGN KEY (proposal_id) REFERENCES advisor_proposal (id) ON DELETE CASCADE,
    CONSTRAINT fk_advisor_conflict_incident FOREIGN KEY (incident_id) REFERENCES incident (id) ON DELETE CASCADE
);
CREATE INDEX ix_advisor_conflict_incident ON advisor_proposal_conflict (incident_id);
